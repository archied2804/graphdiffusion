"""Rebuild the dataset/methodology data figures in the report house style.

These four figures (dataset example, design-space coverage, Cp envelope, and
generated shapes) were previously orphan assets with no generator in the repo.
They are rebuilt here from the HDF5 dataset and the on-disk generated ``.dat``
shapes, in the shared house style, so the whole methodology section is
consistent and reproducible. Writes PNG + PDF to ``docs/assets/`` under the
names the report embeds.

Run from the repository root::

    python scripts/make_report_dataset_figures.py
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _report_style import GREEN, NAVY, apply_house_style  # noqa: E402

from graph_diffusion.data.pOnEllipse import _load_h5_raw  # noqa: E402
from graph_diffusion.visualisation import dataset_overview as do  # noqa: E402

ASSETS = Path("docs/assets")
CFD = Path("cfd/ellipse2d")
H5 = Path("data/ellipse/raw/pOnEllipseTrain.h5")
EXAMPLE_IDX = 2824  # representative sample (Re 750, H 5.5)


def _save(fig: plt.Figure, stem: str) -> None:
    """Write a figure to ``docs/assets/<stem>`` as PNG and PDF."""
    fig.savefig(ASSETS / f"{stem}.png")
    fig.savefig(ASSETS / f"{stem}.pdf")
    plt.close(fig)
    print(f"wrote {stem}.png/.pdf")


def _read_dat(path: Path) -> np.ndarray:
    """Read an ``x y`` polygon .dat (skipping ``#`` comment lines)."""
    pts = []
    for line in path.read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        x, y = line.split()
        pts.append((float(x), float(y)))
    return np.array(pts)


def dataset_example(raw: np.ndarray) -> None:
    """One sample boundary (left) and its steady-mean Cp(x/c) (right)."""
    s = do.sim_summary(raw, EXAMPLE_IDX)
    fig, (axl, axr) = plt.subplots(1, 2, figsize=(10.0, 4.0))
    poly = np.vstack([s["polygon"], s["polygon"][:1]])
    axl.plot(poly[:, 0], poly[:, 1], "-", color=NAVY, lw=1.8)
    axl.fill(poly[:, 0], poly[:, 1], color=NAVY, alpha=0.10)
    axl.set_aspect("equal")
    axl.set_xlabel("$x$")
    axl.set_ylabel("$y$")
    axr.plot(s["x_over_c"], s["cp_curve"], "-", color=NAVY, lw=1.8)
    axr.set_xlabel("$x/c$")
    axr.set_ylabel("$C_p$")
    axr.invert_yaxis()
    fig.tight_layout()
    _save(fig, "report_dataset_example")


def design_space(raw: np.ndarray) -> None:
    """(Re, b) scatter coloured by pressure drag; CFD-validation cases circled."""
    n = raw.shape[0]
    idx = list(range(0, n, 4))
    summ = [do.sim_summary(raw, i) for i in idx]
    re = np.array([d["re"] for d in summ])
    b = np.array([d["b"] for d in summ])
    cd = np.array([d["cd_p"] for d in summ])

    fig, ax = plt.subplots(figsize=(7.2, 5.0))
    sc = ax.scatter(re, b, c=cd, s=10, cmap="viridis", alpha=0.85, edgecolors="none")
    fig.colorbar(sc, ax=ax, label=r"pressure drag $C_{d,p}$")

    manifest = CFD / "shapes" / "eval_grid" / "manifest.csv"
    if manifest.is_file():
        with manifest.open() as fh:
            val_idx = [int(row["idx"]) for row in csv.DictReader(fh)]
        vsumm = [do.sim_summary(raw, i) for i in val_idx]
        ax.scatter(
            [d["re"] for d in vsumm],
            [d["b"] for d in vsumm],
            s=80,
            facecolors="none",
            edgecolors="red",
            linewidths=1.5,
            label="CFD-validation cases",
        )
        ax.legend(loc="upper right")
    ax.set_xlabel("Reynolds number $Re$")
    ax.set_ylabel("semi-minor axis $b$")
    fig.tight_layout()
    _save(fig, "report_design_space")


def cp_envelope(raw: np.ndarray) -> None:
    """All dataset Cp(x/c) curves coloured by minor axis b, with a mean±σ band."""
    n = raw.shape[0]
    idx = list(range(0, n, 3))
    fig = do.plot_cp_envelope(raw, idx, colour_by="b", figsize=(7.2, 5.0))
    for ax in fig.axes:
        if ax.get_title():
            ax.set_title("")
    _save(fig, "report_cp_envelope")


def generated_shapes() -> None:
    """Boundaries generated by the conditional model for the in-dist targets."""
    gen = CFD / "shapes" / "generated"
    cases = [
        ("#4849", "indist_4849_raw.dat", NAVY),
        ("#4066", "indist_4066_raw.dat", GREEN),
    ]
    fig, axes = plt.subplots(
        1, len(cases), figsize=(4.2 * len(cases), 4.0), squeeze=False
    )
    for ax, (label, fname, c) in zip(axes[0], cases, strict=True):
        xy = _read_dat(gen / fname)
        poly = np.vstack([xy, xy[:1]])
        ax.plot(poly[:, 0], poly[:, 1], "-", color=c, lw=1.8)
        ax.fill(poly[:, 0], poly[:, 1], color=c, alpha=0.10)
        ax.set_aspect("equal")
        ax.set_xlabel("$x$")
        ax.set_ylabel("$y$")
        ax.annotate(
            f"target {label}",
            xy=(0.5, 1.02),
            xycoords="axes fraction",
            ha="center",
            va="bottom",
            fontsize=10,
            color="0.3",
        )
    fig.tight_layout()
    _save(fig, "report_generated_shapes")


def main() -> None:
    """Rebuild every dataset/methodology data figure in the house style."""
    apply_house_style()
    ASSETS.mkdir(parents=True, exist_ok=True)
    raw = _load_h5_raw(H5)
    dataset_example(raw)
    design_space(raw)
    cp_envelope(raw)
    generated_shapes()
    print("done.")


if __name__ == "__main__":
    main()
